#!/usr/bin/env python3
"""Builds Engine/TeencodeData.h: the teencode words Vikey keeps when "teencode spelling" is on (D53).
A word typed with a teencode-only rule (z/dz for d, open "ie"/"oy", k after i/ư) stays only if it is here;
anything else goes back to its keys like any invalid word ("zero" doesn't become "zẻo").
Sources: ViSoLex dictionary.json (MIT, © 2024 HaDung2002, github.com/HaDung2002/visolex) and words that occur
at least twice in Vikey's private chat/forum data (counts only, no text). Re-run with both present."""
import glob, json, os, re, unicodedata, collections
HERE = os.path.dirname(os.path.abspath(__file__))
PAT = re.compile(r'^(z|dz)|òy$|[iìíỉĩị]e$|[iíìịỉĩ]k$|[ưừứửữự]k$')
VI = re.compile(r'^[a-zàáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]+$')
TONE = {'́': '1', '̀': '2', '̉': '3', '̃': '4', '̣': '5'}

def canon(w):
    """Engine form: each letter with ^ (â ê ô đ) or + (ă ơ ư), then the tone digit (s f r x j = 1..5)."""
    out, tone = '', ''
    for ch in w:
        if ch == 'đ': out += 'd^'; continue
        d = unicodedata.normalize('NFD', ch)
        out += d[0]
        for m in d[1:]:
            if m == '̂': out += '^'
            elif m in ('̆', '̛'): out += '+'
            elif m in TONE: tone = TONE[m]
    return out + tone

MARKS = re.compile('[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]')
def ok(w):
    # Vietnamese-looking only: a mark, or a short z/dz word (zui, dzai). English names like "annie" stay out.
    return VI.match(w) and PAT.search(w) and not re.search(r'(.)\1\1', w) and len(w) <= 6 and \
           (MARKS.search(w) or (re.match(r'^(z|dz)[aeiouy]', w) and len(w) <= 4))

words = set()
vis = '/tmp/claude-501/visolex/dict/dictionary.json'
if os.path.exists(vis):
    words |= {unicodedata.normalize('NFC', k.lower()) for k in json.load(open(vis))}
cnt = collections.Counter()
for f in glob.glob(os.path.expanduser('~/Work/vikey-data/real/*.txt')) + glob.glob(os.path.expanduser('~/Work/vikey-data/real/fresh/*.txt')):
    for w in re.findall(r'[^\W\d_]+', open(f, encoding='utf-8', errors='ignore').read().lower()):
        cnt[unicodedata.normalize('NFC', w)] += 1
words |= {w for w, c in cnt.items() if c >= 2}
# chat forms named in the request (VietTelex's list) even if rare in our data
NAMED = {'zui', 'zẻ', 'zô', 'zậy', 'dzô', 'bíe', 'thík', 'gòy', 'ừk', 'mịe', 'bik', 'mik', 'thik', 'zìa'}
keep = sorted({canon(w) for w in words if ok(w)} | {canon(w) for w in NAMED})
# Vietnamese scores for the tie rules (same scale as AutoSwitchData: 10*log10(per million)), from our data's counts
def keys(w):
    """The engine's normalized key for the auto-switch tables: aa ee oo dd for ^/đ, aw ow uw for ă ơ ư, tone last."""
    out, tone = '', ''
    for ch in w:
        if ch == 'đ': out += 'dd'; continue
        d = unicodedata.normalize('NFD', ch); out += d[0]
        for m in d[1:]:
            if m == '\u0302': out += d[0]
            elif m in ('\u0306', '\u031b'): out += 'w'
            elif m in TONE: tone = 'sfrxj'[int(TONE[m]) - 1]
    return out + tone
import math
total = sum(cnt.values()) or 1
scored = {}
for w in words:
    if (ok(w) and MARKS.search(w)) or w in NAMED:   # unmarked z-words (zoom, zone, zero) are English: no score
        c = cnt.get(w, 0)
        if c >= 2: scored[keys(w)] = max(scored.get(keys(w), -120), max(-120, min(120, round(10 * math.log10(c / total * 1e6)))))
with open(os.path.join(HERE, '..', '..', 'Engine', 'TeencodeData.h'), 'w') as f:
    f.write('// Generated by Tools/autoswitch/build_teencode.py (D53). Teencode words in the engine\'s letter form\n')
    f.write('// (letter, ^ for â ê ô đ, + for ă ơ ư, tone digit 1-5 last). Sorted for binary search.\n#pragma once\n')
    f.write('static const char* const kTeencodeWords[] = {\n' + ''.join(f'    "{k}",\n' for k in keep) + '};\n')
    f.write(f'static const int kTeencodeCount = {len(keep)};\n')
    sk = sorted(scored)
    f.write('// Vietnamese scores of teencode words that occur in our data, by engine key (zô -> "zoo"), for the tie rules.\n')
    f.write('static const char* const kTeencodeVnKeys[] = {' + ', '.join(f'"{k}"' for k in sk) + '};\n')
    f.write('static const signed char kTeencodeVnScores[] = {' + ', '.join(str(scored[k]) for k in sk) + '};\n')
    f.write(f'static const int kTeencodeVnCount = {len(sk)};\n')
print(len(keep), keep[:40]); print(len(scored), sorted(scored.items(), key=lambda x: -x[1])[:15])
