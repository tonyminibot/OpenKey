#!/usr/bin/env python3
"""Builds eval.jsonl: 500 sentences for the keyboard's Proofread (Apple Intelligence), each with its exact errors.
Generated by the Vikey authors: English grammar items written and annotated by Claude (checked: applying the
listed fixes to the typed text must give the correct text exactly); spelling typos, missing Vietnamese accents and
Telex leftovers are injected by this script into correct sentences Claude wrote. Reproducible with --seed.
  python3 gen_eval.py            (needs ~/.secrets/anthropic_api_key)"""
import json, os, random, re, sys, unicodedata, urllib.request, concurrent.futures as cf
HERE = os.path.dirname(os.path.abspath(__file__))
KEY = open(os.path.expanduser('~/.secrets/anthropic_api_key')).read().strip().split('=')[-1]
MODEL = 'claude-sonnet-5'
TOPICS = ["work chat", "family group", "shopping online", "food and cafes", "travel", "school and exams", "health",
          "football", "movies", "phones and laptops", "renting a flat", "weather", "money and banking", "dating",
          "customer service", "gym", "pets", "moving house", "a party", "a delivery"]

def ask(prompt):
    body = {"model": MODEL, "max_tokens": 8000, "messages": [{"role": "user", "content": prompt}]}
    for _ in range(3):
        try:
            req = urllib.request.Request("https://api.anthropic.com/v1/messages", data=json.dumps(body).encode(),
                headers={"x-api-key": KEY, "anthropic-version": "2023-06-01", "content-type": "application/json"})
            d = json.load(urllib.request.urlopen(req, timeout=600))
            t = "".join(b.get("text", "") for b in d["content"] if b.get("type") == "text")
            m = re.search(r'\[.*\]', t, re.S)
            return json.loads(m.group(0))
        except Exception as e:
            err = e
    print("failed:", err, file=sys.stderr); return []

def grammar_batch(topic):
    return ask(f"""Write 25 short sentences (5-25 words) someone might type on a phone about "{topic}", in casual English,
each containing 1 to 3 GRAMMAR mistakes of the kinds non-native writers make: verb tense (especially with time words like
yesterday / last week / tomorrow / already), subject-verb agreement, plural nouns, articles (a/an/the), pronoun case
(me and him), double negatives, wrong verb forms (buyed, has went), comparatives (more better), prepositions.
Vary the kinds. No spelling mistakes, no names.
For each, give the minimal correction: change ONLY the wrong words; keep everything else exactly (same capitalisation,
same punctuation, same word choice).
Return JSON only: a list of objects {{"typed": "...", "correct": "...", "errors": [{{"typed": "<wrong words exactly as in typed>", "correct": "<replacement exactly as in correct>"}}]}}.
Applying every replacement to "typed" must give exactly "correct".""")

def clean_batch(topic, lang):
    what = {"en": "casual English", "vi": "casual Vietnamese with full, correct diacritics (no English words)",
            "mix": "casual Vietnamese with full diacritics that naturally mixes in a few English words, the way young Vietnamese people text"}[lang]
    return ask(f"""Write 25 short correct sentences (5-25 words) someone might type on a phone about "{topic}", in {what}.
Perfect spelling and grammar. No names, no emoji. Return JSON only: a list of strings.""")

def applies(it):
    t = it["typed"]
    for e in it["errors"]:
        if e["typed"] not in t: return False
        t = t.replace(e["typed"], e["correct"], 1)
    return t == it["correct"] and it["typed"] != it["correct"]

# --- injected errors
ROWS = ["qwertyuiop", "asdfghjkl", "zxcvbnm"]
def neighbour(c, rng):
    for r, row in enumerate(ROWS):
        i = row.find(c)
        if i >= 0:
            n = [row[j] for j in (i - 1, i + 1) if 0 <= j < len(row)]
            return rng.choice(n)
    return c
def typo(w, rng):
    i = rng.randrange(1, len(w) - 1)
    k = rng.choice(["swap", "drop", "double", "near"])
    if k == "swap": return w[:i] + w[i + 1] + w[i] + w[i + 2:]
    if k == "drop": return w[:i] + w[i + 1:]
    if k == "double": return w[:i] + w[i] + w[i:]
    return w[:i] + neighbour(w[i], rng) + w[i + 1:]
def strip_accents(w):
    w = w.replace("đ", "d").replace("Đ", "D")
    return "".join(c for c in unicodedata.normalize("NFD", w) if unicodedata.category(c) != "Mn")
FORMS = {"a": "aàáảãạ", "aw": "ăằắẳẵặ", "aa": "âầấẩẫậ", "e": "eèéẻẽẹ", "ee": "êềếểễệ", "i": "iìíỉĩị", "o": "oòóỏõọ",
         "oo": "ôồốổỗộ", "ow": "ơờớởỡợ", "u": "uùúủũụ", "uw": "ưừứửữự", "y": "yỳýỷỹỵ"}
TONES = ["", "f", "s", "r", "x", "j"]
def telex(w):
    """Keys typed for the word with the tone key last ("bạn" -> "banj"): what shows if the input method was off."""
    out, tone = "", ""
    for c in w:
        lo = c.lower(); up = c != lo
        if lo == "đ": out += "DD" if up else "dd"; continue
        for k, f in FORMS.items():
            if lo in f:
                t = f.index(lo); tone = TONES[t] or tone
                out += (k[0].upper() + k[1:]) if up else k; break
        else: out += c
    return out + tone
def words(s): return re.findall(r"[^\W\d_]+", s)

def inject(sentence, kind, rng):
    ws = [w for w in words(sentence) if len(w) >= 2]
    if kind == "en_spelling":
        cands = [w for w in ws if len(w) >= 4 and w.isascii()]
        pick = rng.sample(cands, min(len(cands), rng.choice([1, 1, 2])))
        mk = lambda w: typo(w, rng)
    elif kind == "vi_accents":
        cands = [w for w in ws if strip_accents(w) != w]
        if rng.random() < 0.4: pick = cands                      # typed with no accents at all
        else: pick = rng.sample(cands, min(len(cands), rng.choice([1, 2, 3])))
        mk = strip_accents
    else:  # vi_telex: the input method was off for a word or two
        cands = [w for w in ws if telex(w) != w]
        pick = rng.sample(cands, min(len(cands), rng.choice([1, 2])))
        mk = telex
    typed, errs = sentence, []
    for w in pick:
        bad = mk(w)
        if bad == w: continue
        m = re.search(r'(?<!\w)' + re.escape(w) + r'(?!\w)', typed)
        if not m: continue
        typed = typed[:m.start()] + bad + typed[m.end():]
        errs.append({"typed": bad, "correct": w})
    return typed, errs

def main():
    rng = random.Random(int(sys.argv[sys.argv.index('--seed') + 1]) if '--seed' in sys.argv else 1)
    with cf.ThreadPoolExecutor(8) as ex:
        gram = [it for b in ex.map(grammar_batch, TOPICS) for it in b]
        cl = {lang: [s for b in ex.map(lambda t: clean_batch(t, lang), TOPICS) for s in b] for lang in ("en", "vi", "mix")}
    gram = [it for it in gram if isinstance(it, dict) and it.get("errors") and applies(it)]
    print(f"grammar items valid: {len(gram)}", file=sys.stderr)
    rng.shuffle(gram)
    for k in cl: rng.shuffle(cl[k])
    items = []
    def add(kind, lang, typed, correct, errs):
        items.append({"id": f"{kind}-{sum(1 for i in items if i['kind'] == kind) + 1:03d}", "kind": kind, "lang": lang,
                      "typed": typed, "correct": correct, "errors": errs})
    for it in gram[:200]: add("en_grammar", "en", it["typed"], it["correct"], it["errors"])
    en, vi, mix = cl["en"], cl["vi"], cl["mix"]
    for s in en[:90]:
        t, e = inject(s, "en_spelling", rng)
        if e: add("en_spelling", "en", t, s, e)
    for s in vi[:80]:
        t, e = inject(s, "vi_accents", rng)
        if e: add("vi_accents", "vi", t, s, e)
    for s in vi[80:130]:
        t, e = inject(s, "vi_telex", rng)
        if e: add("vi_telex", "vi", t, s, e)
    for s in mix[:30]:
        t, e = inject(s, "vi_accents", rng)
        if e: add("mix_accents", "mix", t, s, e)
    for s in mix[30:50]:
        t, e = inject(s, "vi_telex", rng)
        if e: add("mix_telex", "mix", t, s, e)
    for s in en[90:110] + vi[130:150] + mix[50:60]: add("correct", "en" if s in en else "vi" if s in vi else "mix", s, s, [])
    with open(os.path.join(HERE, "eval.jsonl"), "w", encoding="utf-8") as f:
        for it in items: f.write(json.dumps(it, ensure_ascii=False) + "\n")
    from collections import Counter
    print(len(items), dict(Counter(i["kind"] for i in items)), file=sys.stderr)

main()
