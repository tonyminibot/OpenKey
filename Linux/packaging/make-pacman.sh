#!/bin/sh
# Build an Arch Linux (pacman) package from the .deb CPack already made:
#   Linux/packaging/make-pacman.sh Linux/build/vikey_1.0.28_amd64.deb Linux/build
# The payload is the same /usr tree; only the package metadata differs (.PKGINFO, .INSTALL, .MTREE).
# Needs dpkg-deb (to read the .deb) and bsdtar + zstd (to write the .pkg.tar.zst); the Linux CI job installs them.
set -eu

DEB=${1:?usage: make-pacman.sh <vikey_*.deb> <outdir>}
OUT=${2:-$(dirname "$DEB")}

for tool in dpkg-deb bsdtar zstd; do
  command -v "$tool" >/dev/null 2>&1 || { echo "make-pacman.sh: $tool is required" >&2; exit 1; }
done

DEB=$(cd "$(dirname "$DEB")" && pwd)/$(basename "$DEB")
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM

# ---- the .deb's version and architecture become the pacman ones -------------------------------
VER=$(dpkg-deb -f "$DEB" Version)
DEBARCH=$(dpkg-deb -f "$DEB" Architecture)
case "$DEBARCH" in
  amd64) ARCH=x86_64 ;;
  arm64) ARCH=aarch64 ;;
  *) echo "make-pacman.sh: unsupported .deb architecture: $DEBARCH" >&2; exit 1 ;;
esac
case "$VER" in   # a Debian revision (1.0.28-2) is the pacman pkgrel
  *-*) PKGVER=${VER%-*}; PKGREL=${VER##*-} ;;
  *)   PKGVER=$VER; PKGREL=1 ;;
esac

# Arch names for CPACK_DEBIAN_PACKAGE_DEPENDS in Linux/CMakeLists.txt (keep the list in step).
arch_dep() {
  case "$1" in
    ibus)                      echo ibus ;;
    libgtk-4-1)                echo gtk4 ;;
    libadwaita-1-0)            echo libadwaita ;;
    libgstreamer1.0-0)         echo gstreamer ;;
    gstreamer1.0-plugins-base) echo gst-plugins-base ;;
    gstreamer1.0-plugins-good) echo gst-plugins-good ;;
    libnotify-bin)             echo libnotify ;;
    fonts-noto-color-emoji)    echo noto-fonts-emoji ;;
    curl)                      echo curl ;;
    *) return 1 ;;
  esac
}
dpkg-deb -f "$DEB" Depends | tr ',' '\n' | while IFS= read -r dep; do
  dep=$(printf '%s' "$dep" | sed 's/[[:space:]]*(.*//; s/^[[:space:]]*//; s/[[:space:]]*$//')
  [ -n "$dep" ] || continue
  name=$(arch_dep "$dep") || { echo "make-pacman.sh: no Arch name for dependency: $dep" >&2; exit 1; }
  printf 'depend = %s\n' "$name"
done > "$WORK/.PKGINFO.depends"

# ---- payload ------------------------------------------------------------------------------------
dpkg-deb -x "$DEB" "$WORK"
SIZE=$(du -sb "$WORK" | cut -f1)

{
  echo "# Generated by Linux/packaging/make-pacman.sh from $(basename "$DEB")"
  echo "pkgname = vikey"
  echo "pkgbase = vikey"
  echo "pkgver = $PKGVER-$PKGREL"
  echo "pkgdesc = Vikey - Vietnamese input (Telex) with automatic English/Vietnamese switching"
  echo "url = https://vikey.app"
  echo "builddate = $(date +%s)"
  echo "packager = Tony Dinh <patent@tdinh.me>"
  echo "size = $SIZE"
  echo "arch = $ARCH"
  echo "license = GPL-3.0"
  cat "$WORK/.PKGINFO.depends"
  echo "optdepend = desktop-file-utils: refresh the desktop database"
} > "$WORK/.PKGINFO"
rm "$WORK/.PKGINFO.depends"

# The .deb's postinst as pacman's post_install hook (both actions are guarded, as in the postinst).
cat > "$WORK/.INSTALL" <<'EOF'
post_install() {
  if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor 2>/dev/null || true
  fi
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database -q /usr/share/applications 2>/dev/null || true
  fi
}
post_upgrade() {
  post_install
}
EOF

# ---- .MTREE + .pkg.tar.zst, like makepkg: root-owned entries, metadata files first ---------------
(cd "$WORK" && find . -mindepth 1 ! -name .MTREE -printf '%P\0' | LC_ALL=C sort -z | LC_ALL=C bsdtar -cnf - --format=mtree \
  --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' \
  --uid 0 --gid 0 --uname root --gname root --null --files-from - | gzip -c -f -n > .MTREE)

PKG="$OUT/vikey-$PKGVER-$PKGREL-$ARCH.pkg.tar.zst"
rm -f "$PKG"
(cd "$WORK" && find . -mindepth 1 -printf '%P\0' | LC_ALL=C sort -z | LC_ALL=C bsdtar -cf - --uid 0 --gid 0 --uname root --gname root \
  --null --files-from - | zstd -q -T0 -19 -f -o "$PKG")
echo "$PKG"
